def _dur(sec: int) -> str:
    """90 → "1분 30초", 0 → "뺀 상태"."""
    if sec <= 0:
        return "뺀 상태"
    m, s = divmod(sec, 60)
    return f"{m}분{f' {s}초' if s else ''}" if m else f"{s}초"


