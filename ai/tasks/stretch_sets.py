def area_steps(area: str = DEFAULT_AREA) -> list[Step]:
    """한 부위의 5단계(합계 300초). 모르는 부위 값이면 전신."""
    names = ROUTINES.get((area or "").strip().upper(), ROUTINES[DEFAULT_AREA])
    return [Step(i, n, sec, "PLAY", MOVES[n].script) for i, (n, sec) in enumerate(zip(names, SECS), 1)]


def all_area_steps() -> dict[str, list[Step]]:
    """알람이 울릴 때 앱과 AI 세션에 함께 넘기는 5개 루틴 {부위: 단계 목록}."""
    return {a: area_steps(a) for a in AREAS}


def stretch_steps(day: date | None = None) -> list[Step]:
    """기본(부위를 고르기 전) 루틴 = 전신. day는 예전 호출과의 호환용으로 받기만 한다(날짜별 세트 순환은 11/13에 없앰)."""
    return area_steps(DEFAULT_AREA)
