def normalize_area(area: str | None) -> str:
    """부위 값을 12개 중 하나로. 옛 5개 값은 가까운 새 부위로, 모르는 값이면 전신."""
    a = (area or "").strip().upper()
    a = LEGACY_AREAS.get(a, a)
    return a if a in ROUTINES else DEFAULT_AREA


