def pick_stretch_set(day: date | None = None) -> StretchSet:
    """날짜에 따라 4세트를 번갈아 쓴다(같은 날은 항상 같은 세트라 재연결해도 내용이 바뀌지 않는다)."""
    return SETS[(day or date.today()).toordinal() % len(SETS)]


def stretch_steps(day: date | None = None) -> list[Step]:
    return [Step(i, name, sec, "PLAY", script) for i, (name, sec, script) in enumerate(pick_stretch_set(day).steps, 1)]
