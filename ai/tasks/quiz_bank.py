BANKS = {"PERSON": PERSON, "GENERAL": GENERAL}
PER_DAY = 3


def pick_questions(option: str, day: date) -> list[tuple[str, str]]:
    """하루 3문제. 날짜가 하루 지날 때마다 3개씩 건너뛰어 열흘 동안 겹치지 않는다."""
    bank = BANKS[option]
    start = (day.toordinal() * PER_DAY) % len(bank)
    return [bank[(start + k) % len(bank)] for k in range(PER_DAY)]
